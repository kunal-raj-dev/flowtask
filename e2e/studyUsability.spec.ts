import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { assertViewport, plannerErrors, readPlanner, seedPlanner } from './helpers/plannerWorkspace';

test.use({ timezoneId: 'Asia/Kolkata' });
test.afterEach(({ page }) => expect(plannerErrors(page)).toEqual([]));

for (const width of [320, 1440]) test(`study templates edit, persist, duplicate, delete and create real plans at ${width}px`, async ({ page }) => {
  test.setTimeout(120000);
  await page.setViewportSize({ width, height: 900 });
  await seedPlanner(page, { empty: true, theme: width === 320 ? 'dark' : 'light' });
  await page.goto('/app?view=study');
  await page.getByRole('tab', { name: 'Templates', exact: true }).click();
  await page.getByRole('button', { name: 'Edit DSA Practice Sprint', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: 'Edit study template', exact: true });
  await dialog.getByLabel('Template name', { exact: true }).fill('My algebra practice');
  await dialog.getByLabel('Session 1 name', { exact: true }).fill('Algebra revision');
  await dialog.getByLabel('Session 1 target 1 title', { exact: true }).fill('Solve linear equations');
  await dialog.getByLabel('Session 1 target 1 minutes', { exact: true }).fill('20');
  await dialog.getByRole('button', { name: 'Remove target 3 from session 1', exact: true }).click();
  await dialog.getByLabel('Session 1 target 2 title', { exact: true }).fill('Practice quadratics');
  await dialog.getByLabel('Session 1 target 2 minutes', { exact: true }).fill('25');
  await assertViewport(page);
  const accessibility = await new AxeBuilder({ page }).include('.study-planner').withTags(['wcag2a', 'wcag2aa']).analyze();
  expect(accessibility.violations.filter(violation => ['critical', 'serious'].includes(violation.impact || '')).map(violation => violation.id)).toEqual([]);
  await page.screenshot({ path: `screenshots/study-template-editor-${width}.png` });
  await dialog.getByRole('button', { name: 'Save template', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect((await readPlanner(page)).tasks).toHaveLength(0);
  await page.reload();
  await page.getByRole('tab', { name: 'Templates', exact: true }).click();
  const card = page.getByRole('article', { name: 'My algebra practice', exact: true });
  await expect(card.getByText('2 targets · 45m', { exact: true })).toBeVisible();
  await card.getByRole('button', { name: 'Use Template', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Plan a study session', exact: true });
  await expect(dialog.getByLabel('Session 1 target 1 title', { exact: true })).toHaveValue('Solve linear equations');
  expect((await readPlanner(page)).tasks).toHaveLength(0);
  await dialog.getByLabel('Session 1 target 1 title', { exact: true }).fill('Solve advanced linear equations');
  await dialog.getByLabel('Study date', { exact: true }).fill('2026-10-22');
  await dialog.getByLabel('Study project', { exact: true }).selectOption('work');
  await dialog.getByRole('button', { name: 'Create session', exact: true }).click();
  await expect(page.getByRole('tab', { name: /Planned Sessions/ })).toHaveAttribute('aria-selected', 'true');
  const workspace = await readPlanner(page);
  expect(workspace.tasks).toHaveLength(1);
  expect(workspace.tasks[0]).toMatchObject({ plannedDate: '2026-10-22', projectId: 'work', estimatedMinutes: 45 });
  expect(workspace.tasks[0].subtasks.map((target: any) => target.title)).toEqual(['Solve advanced linear equations', 'Practice quadratics']);
  expect(workspace.preferences.workspace.studyTemplates.find((item: any) => item.id === 'dsa').sessions[0].targets[0].title).toBe('Solve linear equations');
  await page.getByRole('tab', { name: 'Templates', exact: true }).click();
  await card.getByRole('button', { name: 'Duplicate My algebra practice', exact: true }).click();
  await page.getByRole('dialog', { name: 'Edit study template' }).getByRole('button', { name: 'Save template', exact: true }).click();
  await expect(page.getByRole('article', { name: 'My algebra practice copy', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete My algebra practice copy', exact: true }).click();
  await expect(page.getByRole('article', { name: 'My algebra practice copy', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('article', { name: 'My algebra practice copy', exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: 'Continue Sprint', exact: true }).click();
  await expect(page.getByText('No active study sprints', { exact: true })).toBeVisible();
});

test('plain-text plans produce editable targets, validate links and start the saved sprint', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await seedPlanner(page, { empty: true });
  await page.goto('/app?view=study');
  await page.getByRole('button', { name: 'Paste a plan', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Plan a study session', exact: true });
  await dialog.getByRole('textbox', { name: 'Study plan text', exact: true }).fill('Math revision:\nTargets:\nRead algebra 20m\nSolve equations 30m\nReview mistakes 10m');
  await expect(dialog.getByText(/1 session · 3 targets found/)).toBeVisible();
  expect((await readPlanner(page)).tasks).toHaveLength(0);
  await dialog.getByRole('button', { name: 'Review & edit targets', exact: true }).click();
  await dialog.getByLabel('Session 1 target 1 title', { exact: true }).fill('Review algebra examples');
  await dialog.locator('.study-target-editor').first().getByText('Difficulty, link & tags', { exact: true }).click();
  await dialog.getByLabel('Session 1 target 1 link', { exact: true }).fill('javascript:alert(1)');
  await expect(dialog.getByRole('button', { name: 'Create session', exact: true })).toBeDisabled();
  await dialog.getByLabel('Session 1 target 1 link', { exact: true }).fill('https://example.com/algebra');
  await dialog.getByLabel('Session 1 target 1 difficulty', { exact: true }).selectOption('MEDIUM');
  await dialog.getByRole('button', { name: 'Move target 3 up in session 1', exact: true }).click();
  await assertViewport(page);
  const scan = await new AxeBuilder({ page }).include('.study-planner').withTags(['wcag2a', 'wcag2aa']).analyze();
  expect(scan.violations.filter(violation => ['critical', 'serious'].includes(violation.impact || '')).map(violation => ({ id: violation.id, targets: violation.nodes.map(node => node.target) }))).toEqual([]);
  await dialog.getByRole('button', { name: 'Create & start', exact: true }).click();
  await expect.poll(async () => (await readPlanner(page)).tasks.length).toBe(1);
  const task = (await readPlanner(page)).tasks[0];
  expect(task.subtasks.map((target: any) => target.title)).toEqual(['Review algebra examples', 'Review mistakes', 'Solve equations']);
  expect(task.estimatedMinutes).toBe(60);
  expect(task.subtasks[0]).toMatchObject({ difficulty: 'MEDIUM', url: 'https://example.com/algebra' });
  const sprint = page.getByRole('dialog', { name: 'Unified Focus Engine', exact: true });
  await expect(sprint.getByRole('heading', { name: 'Review algebra examples', exact: true })).toBeVisible();
  await sprint.getByRole('button', { name: 'Start sprint', exact: true }).click();
  await expect(sprint.getByRole('button', { name: 'Pause sprint', exact: true })).toBeVisible();
  await sprint.getByRole('button', { name: 'Pause sprint', exact: true }).click();
});

test('mobile drafts survive Cancel and refresh, discard is explicit, and account access has one location', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 });
  await seedPlanner(page, { empty: true });
  await page.goto('/app?view=study');
  await expect(page.getByRole('button', { name: 'Cloud Sync and Account Settings', exact: true })).toBeHidden();
  await page.getByRole('button', { name: 'Open navigation menu', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Account and cloud sync', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'New session', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: 'Plan a study session', exact: true });
  await dialog.getByLabel('Session 1 name', { exact: true }).fill('A personal revision plan');
  await dialog.getByLabel('Session 1 target 1 title', { exact: true }).fill('Practice chapter 4');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  expect((await readPlanner(page)).tasks).toHaveLength(0);
  await page.reload();
  await page.getByRole('button', { name: 'New session', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Plan a study session', exact: true });
  await expect(dialog.getByLabel('Session 1 name', { exact: true })).toHaveValue('A personal revision plan');
  await expect(dialog.getByLabel('Session 1 target 1 title', { exact: true })).toHaveValue('Practice chapter 4');
  await assertViewport(page);
  await dialog.getByRole('button', { name: 'Discard draft', exact: true }).click();
  await page.getByRole('button', { name: 'New session', exact: true }).click();
  await expect(page.getByLabel('Session 1 name', { exact: true })).toHaveValue('');
});

